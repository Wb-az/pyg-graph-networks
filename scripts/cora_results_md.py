"""Write docs/cora_results.md from the Cora metrics CSVs and checkpoint configs.

Run after `bash scripts/train_cora_all.sh`:
    uv run python scripts/cora_results_md.py
"""
from pathlib import Path

import pandas as pd
import torch

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "outputs" / "metrics" / "cora"
CHECKPOINTS = ROOT / "outputs" / "checkpoints" / "cora"
OUT = ROOT / "docs" / "cora_results.md"

MODELS = [("gcn", "GCN"), ("gconv", "GConv"), ("gatv2", "GATv2"), ("sage", "GraphSAGE")]
PARAM_KEYS = ["num_layers", "hidden_channels", "heads", "dropout", "lr",
              "weight_decay", "epochs", "early_stop", "seeds"]
METRIC_ROWS = [("Test acc", "Accuracy"), ("Test f1", "Macro F1"),
               ("Test precision", "Precision"), ("Test recall", "Recall"),
               ("Test roc_auc", "ROC AUC"), ("Test avg_precision", "Avg precision"),
               ("Test brier", "Brier"), ("Test ece", "ECE"), ("Test loss", "Loss")]


def config_of(tag: str) -> dict:
    ck = torch.load(CHECKPOINTS / f"cora_{tag}_0_best.pth",
                    map_location="cpu", weights_only=False)
    return ck["config"]


def fmt_param(key: str, value) -> str:
    if key == "seeds":
        return ", ".join(str(int(s)) for s in value)
    return str(value)


def main() -> None:
    configs = {tag: config_of(tag) for tag, _ in MODELS}
    summaries = {tag: pd.read_csv(METRICS / f"{tag}_summary.csv", index_col=0)
                 for tag, _ in MODELS}
    per_seed = {tag: pd.read_csv(METRICS / f"{tag}_results.csv") for tag, _ in MODELS}

    names = [name for _, name in MODELS]
    lines = ["# Cora node classification results", "",
             "Generated by `scripts/cora_results_md.py` from `outputs/metrics/cora` and the",
             "saved checkpoints. Retrain with `bash scripts/train_cora_all.sh`, then rerun",
             "the script to refresh this file.", "",
             "## Training parameters", "",
             "Values that differ from the script defaults are shown in bold.", "",
             "| Parameter | " + " | ".join(names) + " |",
             "|---|" + "---|" * len(names)]
    defaults = {"num_layers": 2, "hidden_channels": 16, "heads": 8, "dropout": 0.5,
                "lr": 0.01, "weight_decay": 5e-4, "epochs": 200, "early_stop": 12,
                "seeds": [0, 1, 2, 3, 4]}
    for key in PARAM_KEYS:
        cells = []
        for tag, _ in MODELS:
            value = configs[tag][key]
            text = fmt_param(key, value)
            if key == "heads" and tag != "gatv2":
                text = "n/a"
            elif value != defaults[key]:
                text = f"**{text}**"
            cells.append(text)
        lines.append(f"| {key} | " + " | ".join(cells) + " |")

    lines += ["", "## Test metrics", "",
              "Mean over the five seeds with the 95 % confidence interval, evaluated on the",
              "Planetoid test split (1000 nodes) at the epoch of lowest validation loss.", "",
              "| Metric | " + " | ".join(names) + " |",
              "|---|" + "---|" * len(names)]
    for row, label in METRIC_ROWS:
        cells = []
        for tag, _ in MODELS:
            s = summaries[tag].loc[row]
            cells.append(f"{s['mean']:.3f} [{s['ci_low']:.3f}, {s['ci_high']:.3f}]")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    lines += ["", "## Per-seed test accuracy", "",
              "| Seed | " + " | ".join(names) + " |",
              "|---|" + "---|" * len(names)]
    seeds = per_seed["gcn"]["seed"].tolist()
    for seed in seeds:
        cells = []
        for tag, _ in MODELS:
            df = per_seed[tag]
            r = df.loc[df["seed"] == seed].iloc[0]
            cells.append(f"{r['acc']:.3f} (epoch {int(r['best_epoch'])})")
        lines.append(f"| {seed} | " + " | ".join(cells) + " |")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
